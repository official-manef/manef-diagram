import assert from 'node:assert/strict';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { build } from 'bun';
import { format, resolveConfig } from 'prettier';

const root = new URL('../', import.meta.url);
const outputPath = new URL('examples/n8n/manef-diagram-converter.json', root);
const staticPath = new URL('static/workflows/manef-diagram-converter.json', root);
const check = process.argv.includes('--check');
assert(
	process.argv.slice(2).every((argument) => argument === '--check'),
	'Use bun scripts/build-n8n-converter.mjs [--check]'
);

const bundled = await build({
	entrypoints: [fileURLToPath(new URL('examples/n8n/converter-entry.ts', root))],
	root: fileURLToPath(root),
	target: 'browser',
	format: 'iife',
	minify: false,
	sourcemap: 'none',
	plugins: [
		{
			name: 'manef-canonical-document',
			setup(builder) {
				builder.onResolve({ filter: /^manef:diagram-core$/ }, () => ({
					path: fileURLToPath(new URL('slices/architecture-inventory/lib/document.ts', root))
				}));
			}
		}
	]
});
assert(bundled.success, bundled.logs.map(String).join('\n'));
assert.equal(bundled.outputs.length, 1, 'The n8n converter must be a single JavaScript bundle.');
const runtime = await bundled.outputs[0].text();
assert(
	!/\b(?:require|fetch|XMLHttpRequest|WebSocket)\s*\(|\bimport\s*(?:\(|["'{*])/.test(runtime),
	'The n8n runtime must not load modules or access the network.'
);
const converter = [
	'// Generated by bun scripts/build-n8n-converter.mjs from the canonical MANEF document core.',
	'// n8n Code node: Run Once for All Items. No credentials, imports, or network access.',
	'let __manefOutput;',
	'function __manefSetResult(items) { __manefOutput = items; }',
	runtime.trim(),
	'return __manefOutput;'
].join('\n');

const sample = {
	format: 'manef-diagram',
	schemaVersion: 1,
	title: 'Synthetic order review',
	graph: {
		schemaVersion: 1,
		nodes: [
			{
				id: 'request',
				label: 'Request',
				tags: ['example'],
				inputs: [],
				outputs: [{ id: 'out', label: 'Order' }],
				views: [
					{
						id: 'sequence',
						kind: 'sequence',
						title: 'Review sequence',
						format: 'md',
						source:
							'sequenceDiagram\n  Request->>Review: Check order\n  Review-->>Request: Approved'
					}
				]
			},
			{
				id: 'review',
				label: 'Review',
				tags: ['example'],
				inputs: [{ id: 'in', label: 'Order' }],
				outputs: [],
				child: {
					schemaVersion: 1,
					nodes: [{ id: 'check', label: 'Check totals', tags: [], inputs: [], outputs: [] }],
					edges: []
				}
			}
		],
		edges: [
			{
				id: 'order-review',
				source: 'request',
				sourcePort: 'out',
				target: 'review',
				targetPort: 'in',
				label: 'Review order'
			}
		]
	},
	ui: {
		diagramMode: 'flow',
		zoom: 1,
		pan: { x: 0, y: 0 },
		positions: { request: { x: 40, y: 80 }, review: { x: 360, y: 80 } }
	},
	extensions: { example: { synthetic: true, order: ['request', 'review'], nullable: null } }
};

const workflow = {
	name: 'MANEF Diagram — JSON and Markdown converter (offline example)',
	active: false,
	nodes: [
		{
			id: 'manef-manual-trigger',
			name: 'Manual Trigger',
			type: 'n8n-nodes-base.manualTrigger',
			typeVersion: 1,
			position: [240, 300],
			parameters: {}
		},
		{
			id: 'manef-synthetic-input',
			name: 'Synthetic example input',
			type: 'n8n-nodes-base.code',
			typeVersion: 2,
			position: [500, 300],
			notes:
				'Synthetic data only. Replace this node with your own input items: {format: "json" | "md", source: "...", target: "json" | "md"}. The converter never substitutes this sample for invalid input.',
			notesInFlow: true,
			parameters: {
				mode: 'runOnceForAllItems',
				language: 'javaScript',
				jsCode: `const document = ${JSON.stringify(sample, null, 2)};\nreturn [{ json: { format: "json", source: JSON.stringify(document), target: "md" } }];`
			}
		},
		{
			id: 'manef-document-converter',
			name: 'MANEF document converter',
			type: 'n8n-nodes-base.code',
			typeVersion: 2,
			position: [800, 300],
			notes:
				'JSON ↔ MANEF Markdown with the same canonical document core as the editor. Returns {document, source, format} per item and retains item linking. Markdown must contain exactly one manef-diagram-json fenced block. Plain Mermaid alone cannot preserve a complete document. Offline Code-node smoke tested; live n8n import/execution is a separate acceptance gate.',
			notesInFlow: true,
			parameters: { mode: 'runOnceForAllItems', language: 'javaScript', jsCode: converter }
		}
	],
	connections: {
		'Manual Trigger': { main: [[{ node: 'Synthetic example input', type: 'main', index: 0 }]] },
		'Synthetic example input': {
			main: [[{ node: 'MANEF document converter', type: 'main', index: 0 }]]
		}
	},
	settings: { executionOrder: 'v1' },
	pinData: {}
};
const text = await format(JSON.stringify(workflow), {
	...(await resolveConfig(fileURLToPath(outputPath))),
	filepath: fileURLToPath(outputPath)
});
for (const path of [outputPath, staticPath]) {
	if (check) {
		assert.equal(
			await readFile(path, 'utf8'),
			text,
			`Stale workflow ${fileURLToPath(path)}; run bun scripts/build-n8n-converter.mjs`
		);
	} else {
		await mkdir(new URL('.', path), { recursive: true });
		await writeFile(path, text);
	}
}
console.log(
	check
		? 'n8n converter workflows match the canonical document source.'
		: 'Wrote n8n example and static download workflows.'
);
